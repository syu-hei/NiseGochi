package com.example.nisegochi.data.persistence

import androidx.room.ColumnInfo
import androidx.room.Entity
import androidx.room.PrimaryKey
import com.example.nisegochi.domain.PetState

@Entity(tableName = "pet_state")
data class PetEntity(
    @PrimaryKey val id: Int = 1,
    val character: String,
    val name: String,
    val state: String,
    val stomach: Int,
    val happy: Int,
    val weight: Int,
    val age: Int,
    val discipline: Int,
    val isAlive: Boolean,
    val isSleeping: Boolean,
    val isDirty: Boolean,
    val isSick: Boolean,
    val isCalling: Boolean,
    val needsDiscipline: Boolean,
    @ColumnInfo(defaultValue = "1") val isLightOn: Boolean,
    @ColumnInfo(defaultValue = "0") val walks: Boolean,
    @ColumnInfo(defaultValue = "0") val isSuperTeen: Boolean,
    @ColumnInfo(defaultValue = "0") val isPaused: Boolean,
    @ColumnInfo(defaultValue = "''") val petName: String,
    @ColumnInfo(defaultValue = "0.0") val totalTimeSeconds: Double,
    @ColumnInfo(defaultValue = "0") val birthTimeMillis: Long,
    @ColumnInfo(defaultValue = "0") val lifespanBonus: Boolean,
    @ColumnInfo(defaultValue = "0") val isDebugMode: Boolean,
    
    // Internal counters/timers
    @ColumnInfo(defaultValue = "0.0") val timeSinceHungryChanged: Double,
    @ColumnInfo(defaultValue = "0.0") val timeSinceHungryEmpty: Double,
    @ColumnInfo(defaultValue = "0.0") val timeSinceHappyChanged: Double,
    @ColumnInfo(defaultValue = "0.0") val timeSinceHappyEmpty: Double,
    @ColumnInfo(defaultValue = "0.0") val timeSinceLastPooped: Double,
    @ColumnInfo(defaultValue = "0.0") val timeSinceDirty: Double,
    @ColumnInfo(defaultValue = "0.0") val timeSinceSick: Double,
    @ColumnInfo(defaultValue = "0.0") val timeSinceNeedsDiscipline: Double,
    @ColumnInfo(defaultValue = "0.0") val timeSinceNeedsLightsOff: Double,
    @ColumnInfo(defaultValue = "0.0") val timeToGetSickFromAge: Double,
    @ColumnInfo(defaultValue = "0.0") val timeForDisciplineCall: Double,
    @ColumnInfo(defaultValue = "0.0") val timeToSleep: Double,
    @ColumnInfo(defaultValue = "0.0") val timeToWake: Double,
    @ColumnInfo(defaultValue = "0.0") val malnutritionTimer: Double,
    @ColumnInfo(defaultValue = "0.0") val obesityTimer: Double,
    @ColumnInfo(defaultValue = "0.0") val disciplineDecayTimer: Double,
    
    // Stats
    @ColumnInfo(defaultValue = "0") val careMisses: Int,
    @ColumnInfo(defaultValue = "0") val disciplineMistakes: Int,
    @ColumnInfo(defaultValue = "0") val cakesEaten: Int,
    
    // Hardcore Mechanics
    @ColumnInfo(defaultValue = "1.0") val metabolismFactor: Double,
    @ColumnInfo(defaultValue = "0.0") val metabolismEndTime: Double,
    val callStartTime: Double?,
    val disciplineCallStartTime: Double?,
    
    // Configuration
    @ColumnInfo(defaultValue = "180") val hungryPeriod: Int,
    @ColumnInfo(defaultValue = "240") val happyPeriod: Int,
    @ColumnInfo(defaultValue = "0") val poopPeriod: Int,
    @ColumnInfo(defaultValue = "19800.0") val disciplineCallPeriod: Double,
    @ColumnInfo(defaultValue = "20") val sleepingHour: Int,
    @ColumnInfo(defaultValue = "9") val wakingHour: Int,
    @ColumnInfo(defaultValue = "5") val idealWeight: Int,
    @ColumnInfo(defaultValue = "0") val yOffset: Int,
    @ColumnInfo(defaultValue = "0") val isMuted: Boolean,
    @ColumnInfo(defaultValue = "''") val pantry: String,
    @ColumnInfo(defaultValue = "0") val selectedPantryIndex: Int,
    @ColumnInfo(defaultValue = "0") val evolutionAnimationCounter: Int,
    @ColumnInfo(defaultValue = "0") val deathAnimationCounter: Int,
    val nextCharacter: String?,

    // Persistence metadata
    @ColumnInfo(defaultValue = "0") val lastUpdatedTimestamp: Long
)

fun PetState.toEntity(timestamp: Long = System.currentTimeMillis()): PetEntity {
    return PetEntity(
        character = character,
        name = name,
        state = state,
        stomach = stomach,
        happy = happy,
        weight = weight,
        age = age,
        discipline = discipline,
        isAlive = isAlive,
        isSleeping = isSleeping,
        isDirty = isDirty,
        isSick = isSick,
        isCalling = isCalling,
        needsDiscipline = needsDiscipline,
        isLightOn = isLightOn,
        walks = walks,
        isSuperTeen = isSuperTeen,
        isPaused = isPaused,
        petName = petName,
        totalTimeSeconds = totalTimeSeconds,
        birthTimeMillis = birthTimeMillis,
        lifespanBonus = lifespanBonus,
        isDebugMode = isDebugMode,
        timeSinceHungryChanged = timeSinceHungryChanged,
        timeSinceHungryEmpty = timeSinceHungryEmpty,
        timeSinceHappyChanged = timeSinceHappyChanged,
        timeSinceHappyEmpty = timeSinceHappyEmpty,
        timeSinceLastPooped = timeSinceLastPooped,
        timeSinceDirty = timeSinceDirty,
        timeSinceSick = timeSinceSick,
        timeSinceNeedsDiscipline = timeSinceNeedsDiscipline,
        timeSinceNeedsLightsOff = timeSinceNeedsLightsOff,
        timeToGetSickFromAge = timeToGetSickFromAge,
        timeForDisciplineCall = timeForDisciplineCall,
        timeToSleep = timeToSleep,
        timeToWake = timeToWake,
        malnutritionTimer = malnutritionTimer,
        obesityTimer = obesityTimer,
        disciplineDecayTimer = disciplineDecayTimer,
        careMisses = careMisses,
        disciplineMistakes = disciplineMistakes,
        cakesEaten = cakesEaten,
        metabolismFactor = metabolismFactor,
        metabolismEndTime = metabolismEndTime,
        callStartTime = callStartTime,
        disciplineCallStartTime = disciplineCallStartTime,
        hungryPeriod = hungryPeriod,
        happyPeriod = happyPeriod,
        poopPeriod = poopPeriod,
        disciplineCallPeriod = disciplineCallPeriod,
        sleepingHour = sleepingHour,
        wakingHour = wakingHour,
        idealWeight = idealWeight,
        yOffset = yOffset,
        isMuted = isMuted,
        pantry = pantry.joinToString(","),
        selectedPantryIndex = selectedPantryIndex,
        evolutionAnimationCounter = evolutionAnimationCounter,
        deathAnimationCounter = deathAnimationCounter,
        nextCharacter = nextCharacter,
        lastUpdatedTimestamp = timestamp
    )
}

